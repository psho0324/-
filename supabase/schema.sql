begin;
create table if not exists public.site_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
create table if not exists public.projects (
  id text primary key check (id ~ '^[a-z0-9][a-z0-9-]{0,59}$'),
  name text not null check (length(btrim(name)) between 1 and 100),
  category text not null default '' check (length(category) <= 50),
  description text not null check (length(btrim(description)) between 1 and 500),
  status text not null default 'building' check (status in ('building','live')),
  tags text[] not null default '{}' check (cardinality(tags) <= 10),
  note text not null default '' check (length(note) <= 10000),
  url text not null default '' check (url = '' or url ~ '^https://'),
  image_url text not null default '' check (image_url = '' or image_url ~ '^https://'),
  show_in_projects boolean not null default true,
  is_published boolean not null default false,
  sort_order integer not null default 0 check (sort_order between 0 and 9999)
);
create table if not exists public.journal_entries (
  id bigint generated by default as identity primary key,
  project_id text not null references public.projects(id) on delete restrict,
  date date not null default current_date,
  title text not null check (length(btrim(title)) between 1 and 200),
  summary text not null check (length(btrim(summary)) between 1 and 1000),
  body text not null check (length(btrim(body)) between 1 and 50000),
  is_published boolean not null default false
);
create index if not exists journal_entries_project_date_idx on public.journal_entries(project_id, date desc);
alter table public.site_admins enable row level security;
alter table public.projects enable row level security;
alter table public.journal_entries enable row level security;

-- 로그인만으로 쓰기 권한을 주지 않습니다. 등록된 관리자만 관리할 수 있습니다.
revoke all on public.site_admins, public.projects, public.journal_entries from anon, authenticated;
grant usage on schema public to anon, authenticated;
grant select on public.site_admins to authenticated;
grant select on public.projects, public.journal_entries to anon;
grant select, insert, update, delete on public.projects, public.journal_entries to authenticated;
grant usage, select on sequence public.journal_entries_id_seq to authenticated;

drop policy if exists workspace_admin_self_read on public.site_admins;
create policy workspace_admin_self_read on public.site_admins for select to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists workspace_project_public_read on public.projects;
create policy workspace_project_public_read on public.projects for select to anon, authenticated
  using (is_published);
drop policy if exists workspace_project_admin on public.projects;
create policy workspace_project_admin on public.projects for all to authenticated
  using (exists (select 1 from public.site_admins where user_id = (select auth.uid())))
  with check (exists (select 1 from public.site_admins where user_id = (select auth.uid())));

drop policy if exists workspace_journal_public_read on public.journal_entries;
create policy workspace_journal_public_read on public.journal_entries for select to anon, authenticated
  using (is_published and exists (select 1 from public.projects p where p.id = project_id and p.is_published));
drop policy if exists workspace_journal_admin on public.journal_entries;
create policy workspace_journal_admin on public.journal_entries for all to authenticated
  using (exists (select 1 from public.site_admins where user_id = (select auth.uid())))
  with check (exists (select 1 from public.site_admins where user_id = (select auth.uid())));

